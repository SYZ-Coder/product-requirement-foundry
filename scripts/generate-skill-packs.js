const fs = require("fs");
const path = require("path");

const definitions = require("./skill-pack-definitions");
const packageJson = require("../package.json");

const repoRoot = path.resolve(__dirname, "..");
const generatedNote = "<!-- Generated by scripts/generate-skill-packs.js. Do not edit by hand. -->";

function writeFile(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content.replace(/\r?\n/g, "\n") + "\n", "utf8");
}

function renderCodexSkill(definition) {
  return `---
name: ${definition.name}
description: ${definition.description}
---

${generatedNote}

${definition.body}`;
}

function renderClaudeSkill(definition) {
  return `---
name: ${definition.name}
description: ${definition.description}
license: MIT
metadata:
  author: product-requirement-foundry
  version: "${packageJson.version}"
---

${generatedNote}

${definition.body}`;
}

for (const definition of definitions) {
  const codexPath = path.join(repoRoot, "skills", definition.name, "SKILL.md");
  const claudePath = path.join(repoRoot, "claude-skills", definition.name, "SKILL.md");
  writeFile(codexPath, renderCodexSkill(definition));
  writeFile(claudePath, renderClaudeSkill(definition));
}

const rootDefinition = definitions.find((definition) => definition.name === "product-requirement-foundry");
writeFile(path.join(repoRoot, "SKILL.md"), renderCodexSkill(rootDefinition));

console.log(`Generated ${definitions.length} Codex skills, ${definitions.length} Claude skills, and root SKILL.md`);
